type SearchEngineIconProps = {
  value: string;
  size?: number;
};

export function SearchEngineIcon({
  value,
  size = 14,
}: SearchEngineIconProps): React.JSX.Element {
  if (value === "bing") {
    return <Bing.Color size={size} />;
  }
  if (value === "brave") {
    return <Brave.Color size={size} />;
  }
  if (value === "google") {
    return <Google.Color size={size} />;
  }
  if (value === "yahoo") {
    // 字标不是正方形：按原始宽高比渲染，高度取 size 的 0.6 倍。
    const height = Math.round(size * 0.6);
    const width = Math.round((height * 264.58333) / 73.375368);
    return (
      <svg
        width={width}
        height={height}
        viewBox="0 0 264.58333 73.375368"
        fill="#7d2eff"
        aria-hidden
        style={{ flex: "none" }}
      >
        <path d={YAHOO_LOGO_PATH} />
      </svg>
    );
  }
  if (value === "duckduckgo") {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="#de5833"
        aria-hidden
        style={{ flex: "none" }}
      >
        <path d={DUCKDUCKGO_LOGO_PATH} />
      </svg>
    );
  }
  if (value === "startpage") {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="#6563ff"
        aria-hidden
        style={{ flex: "none" }}
      >
        <path d={STARTPAGE_LOGO_PATH} />
      </svg>
    );
  }
  if (value === "seznam") {
    // 只取字标左侧的红色「S」，viewBox 按该路径的包围盒裁剪。
    return (
      <svg
        width={size}
        height={size}
        viewBox="0.14 0.51 40.33 41.76"
        fill="#cc0000"
        aria-hidden
        style={{ flex: "none" }}
      >
        <path d={SEZNAM_MARK_PATH} />
      </svg>
    );
  }
  if (value === "yep") {
    return (
      <svg
        width={size}
        height={size}
        viewBox="0 14 82 84"
        aria-hidden
        style={{ flex: "none" }}
      >
        <path d={YEP_BUBBLE_PATH} fill="#fff238" />
        {/* 字母用 currentColor：品牌近黑色在深色主题下会看不清 */}
        <path d={YEP_LETTERS_PATH} fill="currentColor" />
      </svg>
    );
  }
  return <Search size={size} strokeWidth={1.8} />;
}

export function getSearchEngineLabel(value: string): string {
  return (
    SEARCH_ENGINE_OPTIONS.find((option) => option.value === value)?.label ??
    value
  );
}
